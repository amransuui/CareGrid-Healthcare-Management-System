/** Highest waiting-time KPI: longest registered candidate, in days. */
export function longestWaitListedDays(candidates: WaitingListCandidate[]): number {
  const now = Date.now()
  return candidates.reduce((max, candidate) => {
    const days = Math.max(0, Math.floor((now - new Date(candidate.registeredAt).getTime()) / DAY_MS))
    return Math.max(max, days)
  }, 0)
}