const EXPIRY_OFFSETS: Record<string, number> = {
  'O+': 21,
  'O−': 6,
  'A+': 30,
  'A−': 12,
  'B+': 26,
  'B−': 9,
  'AB+': 14,
  'AB−': 5,
}

const COMPONENT_KEYS: Array<{
  key: keyof Omit<InventorySpec, 'bloodGroup'>
  component: BloodInventoryItem['component']
}> = [
  { key: 'wholeBlood', component: 'whole_blood' },
  { key: 'rbc', component: 'rbc' },
  { key: 'platelets', component: 'platelets' },
  { key: 'plasma', component: 'plasma' },
]

export function buildBloodInventory(): BloodInventoryItem[] {
  const items: BloodInventoryItem[] = []
  for (const spec of INVENTORY_SPEC) {
    for (const { key, component } of COMPONENT_KEYS) {
      items.push({
        id: `BI-${spec.bloodGroup.replace('−', 'N')}-${component}`,
        bloodGroup: spec.bloodGroup,
        component,
        units: spec[key],
        expiryDate: daysFromNow(EXPIRY_OFFSETS[spec.bloodGroup]),
        lastUpdated: hoursAgo(3),
      })
    }
  }
  return items
}

