export const patientsSeed: Patient[] = seeds.map((seed) => ({
  ...seed,
  age: computeAge(seed.dateOfBirth),
  admissionDate: isoDaysAgo(seed.admissionDaysAgo, seed.admissionHour),
  notes: clinicalNoteFor(seed),
  lastUpdated: new Date().toISOString(),
}))

export function findPatientSeed(patientId: string): Patient | undefined {
  return patientsSeed.find((patient) => patient.patientId === patientId)
}